// Program: Demonstrate the structure of a C program.

// Preprocessor directive: include declarations for printf.
#include <stdio.h>

int main(void)
{
    // Variable declaration and initialization.
    int number = 10;

    // This statement contains a function call.
    printf("The number is %d.\n", number);

    // The return statement ends main and reports success.
    return 0;
}