// Program: Demonstrate arithmetic operators.

#include <stdio.h>

int main(void)
{
    int a = 10;
    int b = 3;

    printf("Addition: %d\n", a + b);
    printf("Subtraction: %d\n", a - b);
    printf("Multiplication: %d\n", a * b);
    printf("Integer division: %d\n", a / b);
    printf("Remainder: %d\n", a % b);

    return 0;
}